#!/usr/bin/env python3
"""Freeze separately synthesized constant-mode copies of the validated decoder."""
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import struct
import sys

ROOT=Path(__file__).resolve().parents[2]


def main():
    out=ROOT/'data/derived/hls_fixed_modes_20261022_v1'
    out.mkdir(parents=True,exist_ok=False)
    base=ROOT/'hardware/hls'
    fixtures=ROOT/'data/derived/hls_fixtures_20261022_v2'
    manifest=json.loads((fixtures/'manifest.json').read_text())
    for name,digest in manifest['code_sha256'].items():
        if hashlib.sha256((ROOT/name).read_bytes()).hexdigest()!=digest:
            raise ValueError('Audited source changed: '+name)
    source=(base/'graph_expand.cpp').read_text()
    guard='if(node>=c[NODE_COUNT] || c[MODE]>1)return 4;'
    branch='if(c[MODE]==0) {'
    if source.count(guard)!=1 or source.count(branch)!=1:raise ValueError('Unrecognized specialization sites')
    variants={}
    for name,mode in [('csr',0),('compact',1)]:
        directory=out/name;directory.mkdir()
        fixed=source.replace(guard,f'if(node>=c[NODE_COUNT] || c[MODE]!={mode})return 4;')
        fixed=fixed.replace(branch,'if('+('true' if mode==0 else 'false')+') {')
        (directory/'graph_expand.cpp').write_text('// Fixed-mode specialization; generated by prepare_fixed_modes.py.\n'+fixed)
        for filename in ['graph_expand.hpp','test_graph_expand.cpp']:
            (directory/filename).write_bytes((base/filename).read_bytes())
        for label,original in [('full','full'),('rtl','matched')]:
            lines=[]
            for line in (fixtures/(original+'.txt')).read_text().splitlines():
                image,cfg,stimulus=map(Path,line.split())
                if struct.unpack_from('<I',cfg.read_bytes())[0]==mode:lines.append(line)
            if not lines:raise ValueError('No matching stimuli')
            (directory/(label+'.txt')).write_text('\n'.join(lines)+'\n')
        # Fixed hardware must explicitly reject the opposite descriptor mode.
        image,cfg,stimulus=map(Path,lines[0].split())
        data=bytearray(cfg.read_bytes());struct.pack_into('<I',data,0,1-mode)
        badcfg=directory/'wrong_mode.config.bin';badcfg.write_bytes(data)
        case=directory/'wrong_mode.bin'
        case.write_bytes(struct.pack('<4I',2,0,0,2)+struct.pack('<2I',0,1)+struct.pack('<6I',0,0,4,0,0,4))
        for label in ['full','rtl']:
            path=directory/(label+'.txt')
            path.write_text(path.read_text()+' '.join(str(p.resolve()) for p in [image,badcfg,case])+'\n')
        variants[name]={'mode':mode,'source_dir':str(directory.relative_to(ROOT)),
                        'full_batches':len((directory/'full.txt').read_text().splitlines()),
                        'rtl_batches':len((directory/'rtl.txt').read_text().splitlines())}
    r={'created_utc':datetime.now(timezone.utc).isoformat(),'variants':variants,
       'transformation':'Only constant representation branch and descriptor mode guard differ. Interfaces, capacity, ordering and all algorithmic operations are retained.',
       'base_sources':{f:hashlib.sha256((base/f).read_bytes()).hexdigest() for f in ['graph_expand.cpp','graph_expand.hpp','test_graph_expand.cpp']},
       'files':{str(p.relative_to(out)):hashlib.sha256(p.read_bytes()).hexdigest() for p in out.rglob('*') if p.is_file()}}
    (out/'manifest.json').write_text(json.dumps(r,indent=2)+'\n')
    print(json.dumps(r['variants'],indent=2))


if __name__=='__main__':main()
