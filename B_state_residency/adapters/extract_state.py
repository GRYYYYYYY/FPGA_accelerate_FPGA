"""Extract unchanged C++ primitives from the read-only router snapshot.

Fixed textual boundaries deliberately fail closed if the source layout changes.
The surrounding harness supplies a serial host context; this is not the router.
"""
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT.parent / "_shared/assets/gpu_router_original/rewrite/cpp_router/src/main.cpp"


def extract(destination):
    source = SOURCE.read_text()
    ranges = [
        ("NodeDyn", "    struct NodeDyn {", "    std::vector<NodeDyn> dyn;"),
        ("SparseLabels", "    struct SparseLabels {", "    static thread_local SparseLabels* tl_sparse;"),
        ("countUserSlot", "    inline int countUserSlot(", "    inline void promoteOverflowOwner("),
        ("promoteOverflowOwner", "    inline void promoteOverflowOwner(", "    static uint8_t packHotFlags("),
        ("syncHotOcc", "    inline void syncHotOcc(", "    inline int countUserHot("),
        ("inc_decUserSlot", "    inline void incUserSlot(", "    int countConnectionsOfUser("),
        ("rip_commit", "    void ripUp(Connection& c)", "    bool saveRouting("),
        ("gatherShareSet", "    int gatherShareSet(", "\n    // Route ONE expensive connection"),
    ]
    blocks, manifest = [], []
    for name, begin, end in ranges:
        if source.count(begin) != 1 or source.count(end) != 1:
            raise ValueError(f"Source boundary changed: {name}")
        start = source.index(begin)
        stop = source.index(end, start)
        block = source[start:stop]
        blocks.append(block)
        manifest.append({"symbol": name, "start_line": source[:start].count("\n") + 1,
                         "sha256": hashlib.sha256(block.encode()).hexdigest()})
    # Included inside the harness's serial state class.
    content = "// Generated by adapters/extract_state.py; do not edit.\n" + "\n".join(blocks)
    Path(destination).write_text(content)
    return {"source": str(SOURCE), "source_sha256": hashlib.sha256(SOURCE.read_bytes()).hexdigest(),
            "generated_sha256": hashlib.sha256(content.encode()).hexdigest(), "excerpts": manifest}
