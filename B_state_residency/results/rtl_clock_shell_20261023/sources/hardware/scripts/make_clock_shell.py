"""Generate clock-only wrappers and mechanically relocated existing testbenches."""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[2]
PARAMETERS = ['TX_BITS', 'GENERATION_BITS', 'TAG_BITS', 'FRAMES', 'INDEX_BITS']


def generate(destination):
    for variant, suffix in [('baseline', ''), ('wide', '_wide')]:
        module = 'memory_scratch_endpoint' + suffix
        text = (ROOT / f'hardware/rtl/{module}.sv').read_text()
        header = re.search(r'module\s+' + module + r'\s*#\((.*?)\)\s*\((.*?)\);', text, re.S)
        if header is None:
            raise ValueError('Endpoint header changed')
        parameters, ports = header.groups()
        names = []
        for token in ports.split(','):
            token = re.sub(r'\b(input|output|wire|reg)\b|\[[^\]]+\]', '', token).strip()
            if not re.fullmatch(r'[A-Za-z_]\w*', token):
                raise ValueError('Unrecognized port: ' + token)
            names.append(token)
        if len(set(names)) != len(names) or names[:2] != ['clk', 'rst']:
            raise ValueError('Invalid port list')
        wrapper = f'clock_shell_{variant}'
        code = ('`timescale 1ns/1ps\n'
                '// Generated by make_clock_shell.py. Data paths and handshakes are direct.\n'
                f'module {wrapper} #({parameters})({ports.replace("output reg", "output wire")});\n'
                '    wire core_clk;\n'
                '    (* DONT_TOUCH="TRUE" *) BUFG b_clock(.I(clk),.O(core_clk));\n'
                f'    {module} #(\n        ' + ','.join(f'.{p}({p})' for p in PARAMETERS) +
                '\n    ) endpoint(\n        ' + ',\n        '.join(f'.{p}({"core_clk" if p == "clk" else p})' for p in names) +
                '\n    );\nendmodule\n')
        path = destination / f'hardware/rtl/{wrapper}.sv'
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(code)
        tb = (ROOT / f'hardware/tb/tb_memory_endpoint{suffix}.sv').read_text()
        tb = tb.replace(f'memory_endpoint{suffix}_test', f'clock_shell_{variant}_test')
        tb = tb.replace(f'tb_memory_endpoint{suffix}_', f'tb_clock_shell_{variant}_')
        tb = tb.replace(module + ' #(', wrapper + ' #(').replace('dut.', 'dut.endpoint.')
        path = destination / f'hardware/tb/tb_clock_shell_{variant}.sv'
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(tb)


if __name__ == '__main__':
    generate(Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else ROOT)
